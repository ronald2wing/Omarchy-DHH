// Writes js/chirp-metrics.mjs and tests/js/chirp-check-lines.json from the
// JSON dev/measure-chirp.js downloads:
//   node dev/generate-chirp-metrics.mjs ~/Downloads/xcom-metrics.json
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const input = process.argv[2]
if (!input) { console.error("usage: node dev/generate-chirp-metrics.mjs xcom-metrics.json"); process.exit(1) }
const m = JSON.parse(fs.readFileSync(input, "utf8"))
if (!m.emoji) { console.error(input + " has no emoji: run dev/measure-chirp.js again, on an x.com page that shows a post with an emoji"); process.exit(1) }

// Non-ASCII keys as \u escapes, so the file stays plain ASCII.
const key = k => JSON.stringify(k).replace(/[\u007f-\uffff]/g, c => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"))
const table = o => "{" + Object.keys(o).sort().map(k => key(k) + ":" + o[k]).join(",") + "}"
const weight = w => `{\n  advance: ${table(m.weights[w].adv)},\n  kerning: ${table(m.weights[w].kern)}\n}`
const px = s => parseFloat(s) || 0
const measured = Object.values(m.weights).flatMap(w => Object.keys(w.adv))
const advanceLimit = 1 + Math.max(...measured.map(c => c.codePointAt(0)))

const out = `// Chirp's horizontal metrics at x.com's 15px body size, read in x.com's
// own page with dev/measure-chirp.js (canvas measureText on its TwitterChirp
// face): the advance of each character measured, and every kerning
// adjustment of 0.005px or more between two printable ASCII characters,
// regular (400) and bold (700). Used to break and size lines where x.com
// does; the font itself is not shipped. Widths are CSS pixels; a pair's
// kerning adds to the sum of its two advances. Generated by
// dev/generate-chirp-metrics.mjs; do not edit.

export const REGULAR = ${weight("400")}

export const BOLD = ${weight("700")}

// A body emoji: an ${m.emoji.width}px image with its margins either side.
export const EMOJI_ADVANCE = ${m.emoji.width + px(m.emoji.marginLeft) + px(m.emoji.marginRight)}

// One past the highest measured code point: the length of a table indexed by
// code point.
export const ADVANCE_LIMIT = ${advanceLimit}
`
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const write = (relative, text) => {
  fs.writeFileSync(path.join(root, relative), text)
  console.log("wrote", relative)
}
write("js/chirp-metrics.mjs", out)
// The widths x.com's own layout gave whole lines, for tests/js/test_line_layout.mjs.
write("tests/js/chirp-check-lines.json", JSON.stringify(m.check, null, 2) + "\n")
